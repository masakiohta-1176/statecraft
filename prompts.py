def section(title: str, body: str) -> str:
    """
    プロンプトの1セクションを「【見出し】＋本文」の形へ整形する。


        section("ナレッジ", "...") → "【ナレッジ】\\n..."


    本文が空なら、見出しごと空文字を返す。


    見出しと本文を必ずペアで扱うのが要点。プロンプトを文字列連結で
    組み立てると「【ナレッジ】の下に何も無い」という状態が生まれ、
    中身の無い見出しの分だけ毎回トークンを払うことになる。
    ここでペアにしておけば、空のセクションは存在自体が消える。
    """
    if not body:
        return ""
    return f"【{title}】\n{body}"




def join_sections(*parts: str) -> str:
    """
    セクションを空行で区切って連結する。空のセクションは詰めて除く。


    section()が空文字を返したものがそのまま渡ってくるため、
    ここで捨てることで「余分な空行だけが残る」ことも防いでいる。
    """
    return "\n\n".join(p for p in parts if p)





